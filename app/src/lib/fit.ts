/** Wider than anything any of the tables holds, so an unmeasured character can only ever make the
 *  model pessimistic. All three report the same figure, which is why there is one constant. */
const FALLBACK_PX = 15;

/**
 * One number, because the figure face is monospaced: **JetBrains Mono 400 at 14.72px with -0.02em**
 * (`td.fig`), where every character measured — digits, the em dash, the separators — takes the same
 * advance. `tabular-nums` is what makes that exact rather than approximate.
 */
const FIGURE_ADVANCE_PX = 8.71;

/** The same for the units line, **JetBrains Mono 400 at 12px (`--t-xs`), no tracking**. */
const UNITS_ADVANCE_PX = 7;

/**
 * The widest a resolved story score can render. Scores are the one column whose values depend on the
 * view rather than on the shoe (docs/app.md §The story scores), so they are not in the dataset the
 * model is built from — and a stated bound is the honest answer: `displayNumber` gives at most two
 * decimals, so six characters covers `100` and `-12.34` alike, and a score column's header is wider
 * than its figures anyway at every label the registry produces.
 */
const SCORE_CELL_CHARS = 6;

const textPx = (s: string, table: Record<string, number>): number =>
  [...s].reduce((sum, ch) => sum + (table[ch] ?? FALLBACK_PX), 0);

/**
 * What a wrapping box cannot go under: its longest word. The desktop headers wrap deliberately —
 * `nowrap` on a `th` made every column's minimum its longest header — so this, not the whole
 * label, is a header's contribution (docs/app.md §Columns and sorting).
 *
 * A word is `wordsOf`'s: split at the three separators every engine breaks at and drops, hyphens
 * kept. That rule has one home in `labels.ts` and it is deliberate over-reservation rather than a
 * model of anyone's line breaking — the price is a raw slug header wider than the engine would have
 * drawn it, and the alternative is a header hanging out of a declared column in whichever engine
 * the rule was not tuned to.
 */
const widestWordPx = (s: string, table: Record<string, number>): number =>
  Math.max(0, ...wordsOf(s).map((w) => textPx(w, table)));

/**
 * A header's min-content: the name line and the units line, whichever is wider. The caret sits on
 * the NAME line in every column — trailing it in a phrase column, LEADING it in a figure one, so
 * the label can keep the edge its figures keep — so it is counted once, there, and the units line
 * reserves nothing beside it (docs/app.md §Table presentation).
 *
 * ADDITIVE, and that is a fact about the box rather than about the text: the mark and the name are
 * flex items of `.h-line`, and flex items cannot break apart, so the line's minimum is the longest
 * word plus the whole mark. It would not be additive if the mark sat in the text's own flow — the
 * engines break either side of an atomic inline — but that layout was tried and rejected for
 * putting the mark on a line of its own (`ShoeTable.svelte`, `.h-line`).
 */
export function headerMinPx(key: string, test: LabTest | undefined): number {
  // The units line is mono and cannot wrap — no unit string carries a space now that `size-rating`
  // reads `3=TTS`, and `MAX_UNITS_CLEAR_PX` in `labels.ts` is what keeps it that short — so its width is
  // a character count over the whole line (docs/app.md §Table presentation).
  const unitsPx = headerUnits(key, test).length * UNITS_ADVANCE_PX;
  return Math.max(widestWordPx(columnLabel(key, test), HEADER_PX) + CARET_PX, unitsPx);
}

/**
 * A header's max-content: the same two lines, with the name line unwrapped. The sibling of
 * `headerMinPx`, and deliberately built the same way — `textPx` where that takes `widestWordPx`,
 * and the caret and the units line exactly as it reserves them, so the two can only ever differ by
 * how much of the label fits on one line.
 *
 * The units line is the SAME term in both, not a second measurement: it is mono, it carries no
 * space, and `MAX_UNITS_CLEAR_PX` in `labels.ts` is what keeps it short enough never to wrap — so
 * it has one width and this is it (docs/app.md §Table presentation).
 */
export function headerMaxPx(key: string, test: LabTest | undefined): number {
  const unitsPx = headerUnits(key, test).length * UNITS_ADVANCE_PX;
  return Math.max(textPx(columnLabel(key, test), HEADER_PX) + CARET_PX, unitsPx);
}

/**
 * The widest cell in a column. A figure is one mono token, so its width is its length; a phrase
 * carries `white-space: nowrap` and cannot wrap at all, so the whole string is its minimum — which
 * is why the release date column, printing `September 2024`, is one of the widest in the default
 * set (docs/app.md §Table presentation).
 */
export function cellMaxPx(key: string, shoes: readonly Shoe[], idx: TestIndex,
  scoreKeys: ReadonlySet<string>): number {
  if (scoreKeys.has(key)) return SCORE_CELL_CHARS * FIGURE_ADVANCE_PX;
  let widest = 0;
  for (const shoe of shoes) {
    let px: number;
    if (key === 'releasedAt') {
      px = textPx(displayReleaseDate(shoe.releasedAt, shoe.releaseDateSource), PHRASE_PX);
    } else if (key === 'plate') {
      px = textPx(PLATE_LABELS[shoe.plate], PHRASE_PX);
    } else {
      const cat = categoricalValue(shoe, key, idx);
      if (cat !== undefined) px = textPx(cat, PHRASE_PX);
      else {
        const v = key === 'score' ? shoe.score : numericValue(shoe, key, idx);
        px = (v === null || v === undefined ? 1 : displayNumber(v).length) * FIGURE_ADVANCE_PX;
      }
    }
    if (px > widest) widest = px;
  }
  return widest;
}

/**
 * The widest the NAME cell renders, padding excluded — the name column's own `cellMaxPx`, and a
 * function of its own rather than a branch of that one because nothing about it is shared: the cell
 * is a flex row of a chevron, a gap and a name in the bold face, with a chip after the name on the
 * shoes that carry one (`ShoeTable.svelte`, `.name-row`).
 *
 * The name is the one cell in the table that WRAPS, so its minimum is a word rather than a string —
 * `nameCellMinPx` below (docs/app.md §Table presentation).
 */
export function nameCellMaxPx(shoes: readonly Shoe[]): number {
  const widest = Math.max(0, ...shoes.map((s) =>
    textPx(s.name, NAME_PX) + (s.discontinued ? DISC_TAG_PX : 0)));
  return CHEV_PX + NAME_ROW_GAP_PX + widest;
}

/**
 * The same cell at min-content: the chevron, the gap and the widest single WORD the fleet's names
 * carry — `wordsOf`'s word, so `Speedgoat-2024` is one of them and not two. The furniture is
 * additive for the reason `headerMinPx` gives — flex items cannot break apart — and the word rather
 * than the name because this is the one cell that wraps.
 *
 * **The discontinued chip is glued to the name's LAST word, and that is markup rather than
 * choice.** `<strong>{name}</strong><DiscontinuedTag/>` carries no whitespace between the two, and
 * a chip's `margin-left` is not a break opportunity, so no engine breaks there: measured on the
 * real fleet, the widest name cell in the table is `On Cloudmonster` — one 12-character word with
 * the whole chip behind it. A chip trailing a SHORT final word costs the column nothing, since the
 * pair can wrap under a wider word ahead of it, which is why the term is per word and not per name.
 *
 * It is a floor under a floor: `columnPx('name')` takes the wider of this and `NAME_COL_PX`. While
 * the table laid itself out, a name that crossed that floor merely widened the column and only
 * `hunt/fit-boundary.mjs` would have noticed; now that the width is declared it is an overflowing
 * cell instead, and the fleet is upstream's
 * (docs/specs/2026-08-03-virtualising-the-table.md §Decisions).
 */
export function nameCellMinPx(shoes: readonly Shoe[]): number {
  const widest = Math.max(0, ...shoes.map((s) => {
    const parts = wordsOf(s.name);
    return Math.max(0, ...parts.map((w, i) =>
      textPx(w, NAME_PX) + (s.discontinued && i === parts.length - 1 ? DISC_TAG_PX : 0)));
  }));
  return CHEV_PX + NAME_ROW_GAP_PX + widest;
}

/**
 * What the model is: one memoised width per column, over the fleet that is actually loaded. Built
 * once per dataset, because the widest phrase in a column is a fact about the data and nothing a
 * runner does can change it — while the set of columns on screen changes with every tick of the
 * picker, which is why the width is per column and the sum is per call.
 *
 * Both widths answer for `name` as well as for the ticked columns, which no `columns` array ever
 * holds: the name column is the table's first, so a rule that shares a track across the whole table
 * has to be able to ask about it, and a model that answered for one of its two widths and not the
 * other would be a trap for the caller that asked the wrong one.
 */
export interface FitModel {
  /** The column's min-content width including its cell padding. */
  columnPx(key: string): number;
  /** The same column at max-content: what it would take if nothing in it had to wrap. */
  columnMaxPx(key: string): number;
}

/**
 * The score columns, from the pair registry rather than from the scoring engine: a further story
 * arrives here with no edit, and this file needs to know only that these are the columns whose
 * values come from the view rather than from the dataset (docs/app.md §The story scores).
 */
const SCORE_COLUMN_KEYS: ReadonlySet<string> = new Set(
  DERIVED_ZONE_PAIRS.flatMap((p) => [p.heel, p.forefoot]));

/**
 * One model per dataset, wherever it is asked for. The memo is what makes the model cheap — a
 * column's width is a walk of the whole fleet's strings — and two callers building their own
 * instances would each pay for it: `Page.svelte` asks which rendering fits, and `ShoeTable.svelte`
 * asks how to share its track, off the same `data` object.
 *
 * Keyed on the dataset alone, which is sound because `index` is a pure function of `data.tests`
 * (`indexTests`) and every caller derives it that way — the argument exists to avoid recomputing
 * it, never to model a different catalogue over the same shoes. A caller with an index built from
 * anything else must not use this function.
 *
 * A `WeakMap`, so a dataset that goes out of scope takes its widths with it: the suite builds a
 * fresh `ShoesFile` per case and nothing here should outlive one.
 */
const MODELS = new WeakMap<ShoesFile, FitModel>();

export function fitModel(data: ShoesFile, index?: TestIndex): FitModel {
  const cached = MODELS.get(data);
  if (cached) return cached;
  const model = buildFitModel(data, index);
  MODELS.set(data, model);
  return model;
}

function buildFitModel(data: ShoesFile, index?: TestIndex): FitModel {
  const idx = index ?? indexTests(data.tests);
  const mins = new Map<string, number>();
  const maxes = new Map<string, number>();
  const memo = (cache: Map<string, number>, key: string, compute: () => number): number => {
    const hit = cache.get(key);
    if (hit !== undefined) return hit;
    const px = compute();
    cache.set(key, px);
    return px;
  };
  return {
    columnPx(key: string): number {
      // The name column's minimum is `NAME_COL_PX` or the fleet's own longest unbreakable token,
      // whichever is wider (`nameCellMinPx`). The floor is what binds on today's fleet, by a third
      // of a pixel — `fit.test.ts` pins that headroom — and a fleet that crossed it would overflow
      // the cell, the width being declared rather than negotiated with the engine.
      // Reading the whole cell here instead would report the widest whole NAME, which is a
      // max-content and would push every mount decision hundreds of pixels out.
      if (key === 'name') {
        return memo(mins, key, () => Math.max(NAME_COL_PX, nameCellMinPx(data.shoes)) + CELL_PAD_PX);
      }
      return memo(mins, key, () => {
        const test = idx.bySlug.get(key);
        return CELL_PAD_PX + Math.max(headerMinPx(key, test),
          cellMaxPx(key, data.shoes, idx, SCORE_COLUMN_KEYS));
      });
    },
    columnMaxPx(key: string): number {
      return memo(maxes, key, () => {
        const test = idx.bySlug.get(key);
        const cells = key === 'name'
          ? nameCellMaxPx(data.shoes)
          : cellMaxPx(key, data.shoes, idx, SCORE_COLUMN_KEYS);
        return CELL_PAD_PX + Math.max(headerMaxPx(key, test), cells);
      });
    },
  };
}

/**
 * The desktop table's min-content width, panel borders included — what has to fit the content track.
 * The name column comes through the model like every other, which is what keeps the floor it is
 * built on stated once (`columnPx`, above).
 */
export function desktopMinWidth(columns: readonly string[], model: FitModel): number {
  return model.columnPx('name') + WRAPPER_BORDER_PX
    + columns.reduce((sum, col) => sum + model.columnPx(col), 0);
}

/**
 * How the desktop table shares a DECLARED track between its columns — the `<colgroup>`, one width
 * per rendered column with the name column first, summing to `trackPx` exactly.
 *
 * `trackPx` is the table's own width, `WRAPPER_BORDER_PX` excluded: `desktopMinWidth` answers what
 * the PANEL has to be given, and this answers what the table inside it does with what it got.
 *
 * **The table always fills its track**, which is a decision rather than an arithmetic necessity. A
 * model is free not to stretch and a compact table reads better on two columns — but the expanded
 * row lays out against the TABLE's width, not the window's (docs/app.md §The expanded row), so a
 * table left at its natural width lays the panel out in a single stacked column
 * (docs/specs/2026-08-03-virtualising-the-table.md §Decisions).
 *
 * **Two clauses, and the second is the one that is easy to leave out.**
 *
 * 1. While the slack is no more than the columns collectively still want, each column takes
 *    `min + slack × want / Σwant`, where `want` is its own `max − min`. `Released`, `Price`,
 *    `Plate` and `Weight` carry nowrap phrases or unbreakable mono figures and want nothing at all,
 *    so giving them width is waste — the only column that reads better wider is the one that wraps.
 * 2. Past that point every column is at its max and the excess is shared in proportion to
 *    **max-content**. Without this clause a table of figure columns — where every `want` is zero —
 *    gets `0/0` and stops short of its track by the whole excess. The alternative of giving the
 *    excess to the name column was measured and lost: every figure column is right-aligned and the
 *    last one ends at the track's edge whatever happens, so the only thing the rule can move is
 *    where the figures START, and the name column takes them 159px further right at three columns.
 *
 * A column's max is floored at its own min here, and that is not defensive tidying: the name
 * column's minimum is a DECLARED `14rem` floor rather than its content (`columnPx`), so on any
 * fleet whose names are shorter than that the max-content sits UNDER the minimum, and a share taken
 * in proportion to the smaller number would hand that column less than the engine will honour.
 * Flooring makes `want` non-negative and clause two start from a width nothing can clip out of.
 *
 * Negative slack is clamped for the same one-sided reason. This is only ever called where the table
 * has been judged to fit (`rendersPhone`), but a track under the sum of the minimums must overrun
 * the panel rather than clip a cell (spec §Failure behaviour).
 */
export function columnWidths(columns: readonly string[], trackPx: number,
  model: FitModel): number[] {
  const keys = ['name', ...columns];
  const mins = keys.map((k) => model.columnPx(k));
  const maxes = keys.map((k, i) => Math.max(mins[i]!, model.columnMaxPx(k)));
  const totalMin = mins.reduce((a, b) => a + b, 0);
  const totalMax = maxes.reduce((a, b) => a + b, 0);
  const totalWant = totalMax - totalMin;
  const slack = Math.max(0, trackPx - totalMin);
  if (totalWant > 0 && slack <= totalWant) {
    return mins.map((min, i) => min + slack * ((maxes[i]! - min) / totalWant));
  }
  const excess = slack - totalWant;
  return maxes.map((max) => max + excess * (max / totalMax));
}

/**
 * The first layout width at which the sidebar takes a column of its own beside **these** columns:
 * the floor, or the width at which the table still clears the track by the fit rule's own slack,
 * whichever is further out (docs/app.md §Filters).
 *
 * The `max` is the whole rule, and it is what makes the two decisions one. The track costs the table
 * 260px at a single pixel of window, so a permanence boundary that cannot see the column set stands
 * the sidebar up at a width where the fit rule then refuses the table — and the rendering reads
 * desktop → list → desktop as the window is dragged WIDER. Moving the constant closes that for one
 * column set and leaves it open for every wider one — a nine-column view handed 170px of width back
 * to the stacked list at exactly 1191px — because a constant cannot answer a question about a set
 * the runner picks. Consulting the model closes it for every set at once, and gives the stronger
 * property the sidebar was always supposed to have: **it never stands beside the stacked list**,
 * because it waits for the table it exists to tune.
 */
export function sidebarPermanentAt(columns: readonly string[], model: FitModel): number {
  return Math.max(SIDEBAR_PERMANENT_PX,
    desktopMinWidth(columns, model) + FIT_SLACK_PX + CONTENT_GUTTER_PX + SIDEBAR_TRACK_PX);
}

/** Whether the sidebar is a column rather than a drawer at this layout width — the predicate
 *  `Page.svelte` drives the layout, the drawer's focus trap and the `Filters` trigger from, so all
 *  of them answer one boundary (docs/app.md §Filters). */
export function sidebarPermanent(columns: readonly string[], layoutWidth: number,
  model: FitModel): boolean {
  return layoutWidth >= sidebarPermanentAt(columns, model);
}

/** What the table has to lay itself out in: the width less the page's own gutter, less the
 *  sidebar's track wherever the sidebar has one (docs/app.md §Filters). */
export function availableForTable(columns: readonly string[], layoutWidth: number,
  model: FitModel): number {
  return layoutWidth - CONTENT_GUTTER_PX
    - (sidebarPermanent(columns, layoutWidth, model) ? SIDEBAR_TRACK_PX : 0);
}

/** The question in one line: would the desktop table fit, with the slack it is held to? */
export function fitsDesktop(columns: readonly string[], availableWidth: number,
  model: FitModel): boolean {
  return desktopMinWidth(columns, model) + FIT_SLACK_PX <= availableWidth;
}

/**
 * The mount decision itself, so the floor and the fit rule have one home and `Page.svelte` reads a
 * single predicate. `layoutWidth` is the LAYOUT width — `documentElement.clientWidth`, which excludes
 * a classic scrollbar — because that is the width the table is laid out in and the fleet is always
 * long enough to draw one.
 *
 * Monotone in the width by construction, which is the property that matters most here: below
 * `sidebarPermanentAt` the available width is `layoutWidth - 16` and rises with the window, above it
 * `layoutWidth - 276`, and the boundary is *defined* as a width at which the second still clears the
 * table's minimum. So the step down at the boundary can never cross the requirement, and a rendering
 * once mounted survives every wider window
 * (docs/app.md §Two renderings, and only one of them mounted).
 */
export function rendersPhone(columns: readonly string[], layoutWidth: number,
  model: FitModel): boolean {
  if (layoutWidth < DESKTOP_FLOOR_PX) return true;
  return !fitsDesktop(columns, availableForTable(columns, layoutWidth, model), model);
}
