/**
 * How wide the desktop table's columns are, in pixels, computed rather than measured — the whole
 * point being that they can be asked BEFORE the table is mounted, so `Page.svelte` picks the
 * rendering that fits instead of mounting one and watching it overflow
 * (docs/app.md §Two renderings, and only one of them mounted).
 *
 * Two widths per column, and they answer different questions. The **min-content** half is what the
 * table has to have, and it decides which rendering mounts. The **max-content** half is what a
 * column would take if nothing in it had to wrap; it decides nothing on its own, and exists for a
 * rule that shares a declared track between columns.
 *
 * Nothing here touches the DOM. A model that measured a mounted table could only ever answer for the
 * rendering already on screen, and switching on that answer is a feedback loop: mount the desktop
 * table, measure it too wide, mount the phone one, measure nothing, mount the desktop table again.
 *
 * The inputs are of three kinds and it is worth knowing which is which when one of them moves:
 *
 * 1. **Tokens** — the paddings, the name column, the caret. Read off `app.css` and `ShoeTable.svelte`
 *    and listed once, below. The name column's floor is the one exception and says so where it is
 *    written: a declared width leaves no cell floor for it to transcribe.
 * 2. **Font tables** — generated by `app/scripts/measure-label-widths.mjs` and committed. Each is
 *    specific to a face, a size, a weight AND a tracking; the block above each one names all four.
 * 3. **The loaded fleet** — the widest string each phrase column actually renders, which no constant
 *    can state because it is upstream's. Computed once per dataset and memoised by `fitModel`.
 */

/* ─ tokens ─ The one home for the geometry this model is built out of. Every number is a CSS
   declaration this file cannot see, so each names where it is written. */
